import type {ValueOf} from '../../schemaTypes/constants'
import {AMENITIES, BED_TYPES, CHECK_IN_METHODS, PROPERTY_TYPES} from '../../schemaTypes/constants'
import type {PhotoId} from './photos'

type BedType = ValueOf<typeof BED_TYPES>
type Bed = BedType | [BedType, number]

export type SeedRoom = {name: string; beds: {type: BedType; count: number}[]}

export type SeedProperty = {
  slug: string
  title: string
  propertyType: ValueOf<typeof PROPERTY_TYPES>
  featured: boolean
  host: string
  cancellation: 'flexible-cancellation' | 'moderate-cancellation' | 'strict-cancellation'
  location: {city: string; region: string; country: string}
  photos: [PhotoId, PhotoId, PhotoId]
  summary: string
  description: string
  highlights: string[]
  pricePerNight: number
  cleaningFee: number
  minNights: number
  maxGuests: number
  bedrooms: number
  bathrooms: number
  rooms: SeedRoom[]
  amenities: ValueOf<typeof AMENITIES>[]
  houseRules: {
    petsAllowed: boolean
    smokingAllowed: boolean
    partiesAllowed: boolean
    quietHours?: {start: string; end: string}
    checkInTime: string
    checkOutTime: string
    checkInMethod: ValueOf<typeof CHECK_IN_METHODS>
    additionalRules: string[]
  }
  rating: number
  reviewCount: number
}

const room = (name: string, ...beds: Bed[]): SeedRoom => ({
  name,
  beds: beds.map((bed) =>
    Array.isArray(bed) ? {type: bed[0], count: bed[1]} : {type: bed, count: 1},
  ),
})

const us = (city: string, region: string) => ({city, region, country: 'United States'})

const rules = (
  overrides: Partial<SeedProperty['houseRules']> & Pick<SeedProperty['houseRules'], 'petsAllowed'>,
): SeedProperty['houseRules'] => ({
  smokingAllowed: false,
  partiesAllowed: false,
  quietHours: {start: '22:00', end: '08:00'},
  checkInTime: '16:00',
  checkOutTime: '11:00',
  checkInMethod: 'keypad',
  additionalRules: [],
  ...overrides,
})

